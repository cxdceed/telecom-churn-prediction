def build(name, cells):
    nb = nbf.v4.new_notebook()
    nb.cells = cells
    nb.metadata["kernelspec"] = {"display_name": "Python 3", "language": "python", "name": "python3"}
    ExecutePreprocessor(timeout=600, kernel_name="python3").preprocess(nb, {"metadata": {"path": str(C.ROOT / "notebooks")}})
    nbf.write(nb, str(C.ROOT / "notebooks" / name))
    print("wrote", name)


def main():
    build("01_eda.ipynb", nb_eda())
    build("02_modeling.ipynb", nb_model())
    build("03_evaluation_and_business_case.ipynb", nb_eval())


if __name__ == "__main__":
    main()
